// Shared helpers: paths, config, episode IO, shell, media probing.
import fs from "node:fs";
import path from "node:path";
import { execFileSync, spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const PIPE = path.join(ROOT, "pipeline");
export const RUNTIME = path.join(PIPE, "runtime"); // generated by setup.mjs (gsap, fonts, textures)

export function loadChannel() {
  return JSON.parse(fs.readFileSync(path.join(ROOT, "channel.json"), "utf8"));
}

export function episodeDir(slug) {
  if (!slug) die("Missing episode slug. Usage: node pipeline/<script>.mjs <slug>");
  const dir = path.join(ROOT, "episodes", slug);
  if (!fs.existsSync(dir)) die(`No episode folder: episodes/${slug}`);
  return dir;
}

export function readJSON(file, fallback) {
  if (!fs.existsSync(file)) {
    if (fallback !== undefined) return fallback;
    die(`Missing file: ${path.relative(ROOT, file)}`);
  }
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (e) {
    die(`Invalid JSON in ${path.relative(ROOT, file)}: ${e.message}`);
  }
}

export function writeJSON(file, data) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + "\n");
}

export function die(msg) {
  console.error(`\n✗ ${msg}\n`);
  process.exit(1);
}

export function log(msg) {
  console.log(msg);
}

export function slugify(s) {
  return s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
}

/** Run a command, streaming output. Throws on non-zero exit. */
export function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: opts.quiet ? "pipe" : "inherit", encoding: "utf8", ...opts });
  if (r.status !== 0) {
    const out = opts.quiet ? `\n${r.stdout || ""}${r.stderr || ""}` : "";
    throw new Error(`${cmd} ${args.join(" ")} exited with ${r.status}${out}`);
  }
  return r;
}

export function hf(args, opts = {}) {
  // Use the project-local HyperFrames CLI so versions stay pinned.
  const bin = path.join(ROOT, "node_modules", ".bin", "hyperframes");
  return run(fs.existsSync(bin) ? bin : "npx", fs.existsSync(bin) ? args : ["hyperframes", ...args], opts);
}

export function mediaDuration(file) {
  const out = execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file], {
    encoding: "utf8",
  });
  return parseFloat(out.trim());
}

export function imageSize(file) {
  const out = execFileSync(
    "ffprobe",
    ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "csv=p=0:s=x", file],
    { encoding: "utf8" },
  );
  const [w, h] = out.trim().split("x").map(Number);
  return { w, h };
}

export function hashString(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return (h >>> 0).toString(16).padStart(8, "0");
}

export function esc(s = "") {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function fmtTime(sec) {
  const s = Math.max(0, Math.floor(sec));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const r = s % 60;
  return h ? `${h}:${String(m).padStart(2, "0")}:${String(r).padStart(2, "0")}` : `${m}:${String(r).padStart(2, "0")}`;
}

export function rel(p) {
  return path.relative(ROOT, p);
}
